-- 명단·계정 짝짓기(link_member_account)를 걷어낸다.
--
-- 왜 실패했는가:
--   명단 행을 남기고 계정 행을 지우도록 만들었다. 명단 쪽에 쌓인 경기
--   기록을 지키려는 의도였는데, 계정 행에 붙어 있던 것들이 함께 사라진다.
--   특히 group_id 가 그렇다.
--
--   실제 흐름은 이렇다:
--     주최자가 명단에 '김철수' 를 넣는다        → 조 미정
--     김철수가 코드로 들어와 자기 조를 고른다   → 2조
--     관리자가 둘을 잇는다                      → 2조가 사라진다
--
--   본인이 고른 조가 조용히 날아가는 건 고칠 수 있는 버그가 아니라
--   합치는 방향 자체가 잘못 잡힌 것이다. 어느 쪽 정보를 남길지는
--   행 단위가 아니라 칸 단위로 정해야 하고(이름은 명단, 조는 계정 …),
--   그건 규칙을 먼저 세운 뒤에 다시 만드는 게 맞다.
--
-- 그때까지는 아예 부를 수 없게 지운다. 반쯤 맞는 경로를 열어 두면
-- 누군가는 그걸 쓰고, 조가 날아간 걸 한참 뒤에 발견한다.
--
-- 명단 추가(add_roster_member)와 제외(remove_member)는 그대로 둔다.
-- ════════════════════════════════════════════════════════════════════

