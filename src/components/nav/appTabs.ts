/**
 * 전역 하단탭이 **어느 화면에 뜨는지**를 정하는 규칙 하나.
 *
 * 컴포넌트가 아니라 순수 함수로 떼어 둔다. "두 탭바가 겹치지 않는다" ·
 * "게스트 화면에는 없다" 는 렌더링이 아니라 **규칙**이라, 화면을 띄우지
 * 않고도 검사할 수 있어야 한다.
 *
 * ── 왜 전역 탭이 필요한가 ──────────────────────────────────────────
 *
 * `docs/design.md` 의 「구조 — 하단탭으로 내린다」는 이미 원칙으로 서
 * 있었는데 **대회·모임 안에서만** 지켜졌다(`TournamentTabBar`). 밖으로
 * 나오면 탭이 사라지고 링크 목록만 남아서, 같은 앱인데 화면마다 구조가
 * 달랐다. 앱은 어디에 있든 같은 자리에 같은 탭이 있다.
 *
 * ── 탭 넷인 근거 ───────────────────────────────────────────────────
 *
 * `TournamentTabBar` 주석은 "엄지 하나가 좌우로 훑는 자리라 5개가 한계"
 * 라고 적었고, 거기는 갈 곳이 여섯이라 다섯까지 썼다. 대회 밖에는
 * **장소가 넷뿐**이다 — 오늘(`/`) · 동아리 · 내 목록 · 나.
 *
 * 나머지(모임 열기 · 대회 만들기 · 참가하기)는 장소가 아니라 **동작**이다.
 * 탭바는 "어디" 를 고르는 자리지 "무엇을 한다" 를 고르는 자리가 아니다 —
 * 동작을 탭으로 올리면 누를 때마다 시트가 열려 오히려 한 탭이 는다.
 * 그래서 동작은 각자 있어야 할 장소로 내려보낸다(모임 열기 → 오늘,
 * 대회 만들기·참가하기 → 내 목록, 동아리 만들기·코드 → 동아리).
 *
 * '기록' 을 넣지 않은 이유는 따로 있다. 전역에는 기록 화면이 없고,
 * `/my` 는 참가한 대회·모임의 **목록**이다. 게다가 '기록' 은 이미
 * `TournamentTabBar` 에서 경기 기록을 뜻한다 — 같은 글자가 두 탭바에서
 * 다른 곳으로 가면 어느 쪽이 맞는지 아무도 모르게 된다.
 */
export type AppTab = 'home' | 'clubs' | 'list' | 'me'

/**
 * 탭이 뜨는 화면 — **허용 목록**이다. 접두사로 넓게 잡지 않는다.
 *
 * 새 화면을 만드는 사람이 여기 한 줄을 더하지 않으면 탭이 안 뜬다. 그게
 * 맞는 기본값이다 — 폼 화면에 탭이 딸려 들어와 입력하던 것이 날아가는
 * 쪽이 훨씬 나쁘다.
 */
const PLACES: Readonly<Record<string, AppTab>> = {
  '/': 'home',
  '/clubs': 'clubs',
  '/my': 'list',
  '/me': 'me',
  // 알림은 '나' 의 하위 화면이다 — 계정·기기에 붙는 것이라 대회 밑이 아니다
  '/settings/alerts': 'me',
}

/**
 * 동아리 하위 화면(`/c/:id`, `/c/:id/members` …)은 전부 '동아리' 탭이다.
 *
 * 여기만 접두사로 잡는 이유: 동아리 탭은 동아리가 하나뿐인 사람을
 * `/c/:id` 로 바로 보낸다(`AppTabBar`). 그 화면에서 탭이 사라지면 **탭을
 * 누른 결과가 탭을 없애는** 꼴이 된다. 동아리 하위 화면에는 하단 고정
 * CTA 가 하나도 없어서(`grep 'fixed inset-x-0 bottom-0'`) 겹칠 것도 없다.
 */
const CLUB_PREFIX = '/c/'

/**
 * 탭이 **뜨지 않는 곳**과 그 이유.
 *
 * - `/t/**` — `TournamentTabBar` 의 자리다. 두 탭바가 동시에 뜨면 안 된다.
 *   ⚠ 저 탭바는 대회 **안**에서만 오간다. 대회 밖으로 나가는 길은
 *   머리말 하나뿐이라(`TournamentNav`) 거기만은 위쪽 이동이 남는다.
 * - `/g/**` — 게스트. 계정이 없는 사람에게 `/` 는 로그인 화면이라 탭 넷이
 *   전부 막다른 길이다(`BackBar` 가 게스트 화면에서 홈을 끄는 것과 같은
 *   근거, `guestScreensHaveNoHome.test.tsx`).
 * - `/login` · `/auth/callback` — 아직 사람이 없다.
 * - `/new` · `/new/session` · `/join` · `/clubs/new` · `/clubs/join` —
 *   **작업 화면**이다. 한 가지를 끝내러 들어온 곳이고, 탭으로 새면 입력한
 *   것이 사라진다. 여기의 출구는 머리말의 링크 하나다(`BackBar`) — 어디로
 *   나가는지 글자로 적혀 있어야 한다('메인으로' · '내 동아리').
 *
 * 이 목록은 위 허용 목록에 없어서 저절로 지켜진다. 적어 두는 것은
 * 근거를 남기기 위해서다.
 */
export function appTabFor(pathname: string): AppTab | null {
  const path = normalize(pathname)
  if (path.startsWith(CLUB_PREFIX)) return 'clubs'
  return PLACES[path] ?? null
}

/** 끝의 `/` 는 같은 화면이다. `/my/` 로 들어와도 탭이 켜져야 한다 */
function normalize(pathname: string): string {
  if (pathname.length > 1 && pathname.endsWith('/')) return pathname.slice(0, -1)
  return pathname
}

/**
 * 하단탭에 가리지 않으려고 본문이 져야 하는 아래 여백.
 *
 * `position: fixed` 는 문서 흐름을 밀지 않는다(`docs/ui-redesign.md` —
 * "코트 칩을 목록 아래로 내렸더니 고정 바 뒤에 깔려 사라졌다"). 그래서
 * 탭이 뜨는 화면은 스스로 이만큼 비워야 한다.
 *
 * 5.5rem = 탭 한 줄(4rem, `min-h-16`) + 숨 쉴 자리. `TournamentPage` 가
 * 같은 값을 쓴다 — 두 탭바의 높이가 같으므로 여백도 같아야 한다.
 */
export const APP_TAB_PADDING = 'calc(5.5rem + env(safe-area-inset-bottom))'
