import { useEffect, useRef } from 'react'
import type { RsvpStatus } from '@/types/database'

/**
 * 모임 화면을 열면 **참가로 표시한다.**
 *
 * ── 왜 기본값을 뒤집었나 ────────────────────────────────────────────
 *
 * 전에는 `참가할게요` 를 눌러야 참가였다. 그런데 **여기까지 들어온 사람은
 * 대개 온다** — 모임 화면을 일부러 열었다는 것 자체가 "간다" 에 가깝다.
 * 오는 사람이 매번 버튼을 눌러야 하고, 안 누른 사람이 미정으로 쌓여
 * 모임장이 "몇 명 오나" 를 못 읽는 쪽이 더 나빴다.
 *
 * 그래서 들어오면 참가이고, 못 오는 사람만 `모임 나가기` 를 누른다.
 *
 * ── 바꾸지 않는 세 경우 ─────────────────────────────────────────────
 *
 * 1. **이미 참가**(`going`) — 쓸 이유가 없다
 * 2. **불참을 눌렀다**(`declined`) — 되돌리면 그 사람이 화면을 볼 때마다
 *    자기가 누른 것이 뒤집힌다. **앱이 자기 말을 안 듣는 것**으로 읽힌다
 * 3. **명단에 없다**(`me` 없음) — 누를 주체가 없다
 *
 * 즉 `invited`(아직 아무것도 안 누름) 하나만 바꾼다.
 *
 * ── 한 번만 시도한다 ────────────────────────────────────────────────
 *
 * 실패해도 다시 걸지 않는다. 명단·모임 조회가 갱신될 때마다(포커스 복귀 ·
 * 폴링 · 실시간) 이 훅이 다시 도는데, 거기서 재시도하면 **권한이 없거나
 * 시각이 지난 모임에서 서버를 끝없이 때린다.** 실패는 화면이 오류로
 * 말하고, 사람이 버튼으로 다시 누를 수 있다.
 *
 * ⚠ 이건 화면을 여는 것만으로 서버에 쓰는 드문 자리다. 그래서 화면이
 * **"참가로 표시했습니다" 라고 먼저 말한다**(`SessionRsvpPanel`). 조용히
 * 바뀌면 사람은 자기가 뭘 했는지 모른다.
 */
export function useAutoJoin({
  rsvp,
  enabled,
  onJoin,
}: {
  /** 내 참가 상태. 명단에 없으면 undefined */
  rsvp: RsvpStatus | undefined
  /** 시작 전 모임 화면인가 — 지난 모임에서는 쓰지 않는다 */
  enabled: boolean
  onJoin: () => void
}) {
  const tried = useRef(false)

  useEffect(() => {
    if (tried.current) return
    if (!enabled) return
    if (rsvp !== 'invited') return

    tried.current = true
    onJoin()
    // onJoin 은 뮤테이션이라 렌더마다 새 함수일 수 있다. tried 로 이미
    // 한 번만 돌게 막았으므로 의존성에 넣어도 되지만, 넣으면 "왜 안
    // 도는가" 를 읽는 사람이 tried 와 의존성 둘을 같이 봐야 한다.
  }, [rsvp, enabled, onJoin])
}
