import { cn } from '@/lib/utils'

/**
 * 코트 번호 옆 작은 정비율 코트 도형.
 *
 * v6 · v7 리뷰(찍어서 봄)에서 카드 전체를 코트 비율로 늘리는 배경 마킹을
 * 두 번 고쳤다 — 서비스 박스를 네트 쪽으로 붙이고, 카드 자체 테두리를
 * 코트 경계로 재사용해도 봤다. 그래도 카드가 5:1 에 가까운 가로로 긴
 * 비율이라 "빈 표 셀 두 개" 로만 보이고 코트로 안 읽혔다(코디네이터
 * 확인 — 두 번의 시도로 결론 남).
 *
 * 그래서 방향을 바꿨다 — **정비율(실제 코트 13.4:6.1 ≈ 2.2:1)을 지키는
 * 작은 도형 하나**를 코트 번호 옆에 따로 두고, 그 안에 필요한 선을
 * 전부(바깥 경계 · 네트 · 숏 서비스 라인 · 센터 라인) 그린다. 작은
 * 도형은 비율만 맞으면 선이 여러 개 있어도 지저분해지지 않는다 —
 * 오히려 있어야 코트로 읽힌다. **다음 사람이 전폭 배경 마킹을 또
 * 시도하지 않도록 이 판단을 여기 남긴다.**
 *
 * 카드 가운데를 가르는 배경 네트(두 줄, CourtBoard 의 CourtLines) 는
 * 그대로 살아 있다 — 그건 이미 잘 읽힌다는 확인을 받았다. 이 도형은
 * 그것과 별개로, "코트 전체" 를 작게 다시 보여주는 두 번째 마킹이다.
 *
 * 상태는 진하기로 말한다 — 빈 코트는 또렷하고, 진행 중인 코트는 옅다.
 * 사람이 들어찬 걸 점 두 개씩(4개)으로 표시하는 안도 검토했지만, 40×18
 * 크기에서는 안 읽힐 위험이 커서(코디네이터도 "무리하지 마라" 라고 함)
 * 무리하지 않고 진하기 차이만 남겼다.
 */
export function CourtBadge({ faint }: { faint: boolean }) {
  const stroke = {
    fill: 'none',
    stroke: 'currentColor',
    strokeWidth: 1,
    vectorEffect: 'non-scaling-stroke' as const,
  }

  return (
    <svg
      aria-hidden="true"
      focusable="false"
      viewBox="0 0 40 18"
      className={cn(
        'h-[18px] w-10 shrink-0 text-court-line',
        faint ? 'opacity-[0.35]' : 'opacity-[0.9]',
      )}
    >
      {/* 바깥 경계 — 작은 도형 안에서는 이게 있어야 '코트'로 읽힌다 */}
      <rect x="1" y="1" width="38" height="16" {...stroke} />
      {/* 네트 — 두 줄이라 '구분선'이 아니라 '네트'로 읽힌다 */}
      <line x1="19.3" y1="1" x2="19.3" y2="17" {...stroke} />
      <line x1="20.7" y1="1" x2="20.7" y2="17" {...stroke} />
      {/* 숏 서비스 라인 — 네트 가까이, 좌우 대칭 */}
      <line x1="14" y1="1" x2="14" y2="17" {...stroke} />
      <line x1="26" y1="1" x2="26" y2="17" {...stroke} />
      {/* 센터 라인 — 네트에서 바깥 경계까지, 서비스 코트를 위아래로 가른다 */}
      <line x1="1" y1="9" x2="19.3" y2="9" {...stroke} />
      <line x1="20.7" y1="9" x2="39" y2="9" {...stroke} />
    </svg>
  )
}
